/**
 * npm run live:report — reads every round from the live coordinator and writes docs/LIVE.md:
 * the live column of "Simulated vs live", dated, plus one row per round (asks, winners, forfeits).
 * Read-only: needs no keys. CONTRACT=... to read another coordinator.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { formatUsdc, headline } from '@hivebuy/core';

const CONTRACT = process.env.CONTRACT ?? 'market.hivebuy.testnet';
const RPC = process.env.NEAR_RPC_URL ?? 'https://test.rpc.fastnear.com';
const NOTES = resolve('apps', 'web', 'public', 'agent-notes', `${CONTRACT}.json`);

interface Round {
  id: number;
  buyers: { account_id: string; qty: number; max_price: string }[];
  sellers: { account_id: string; commit_index: number; revealed: { price: string; capacity: number } | null }[];
  outcome: { price: string | null; demand: number } | null;
  fills: { account_id: string; units: number }[];
  price_set_by: string | null;
}

async function view<T>(method: string, args: object): Promise<T> {
  const res = await fetch(RPC, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 'live-report', method: 'query', params: { request_type: 'call_function', finality: 'final', account_id: CONTRACT, method_name: method, args_base64: Buffer.from(JSON.stringify(args)).toString('base64') } }),
    signal: AbortSignal.timeout(20_000),
  });
  const body = (await res.json()) as { result?: { result: number[] }; error?: unknown };
  if (!body.result) throw new Error(`RPC error: ${JSON.stringify(body.error)}`);
  return JSON.parse(Buffer.from(body.result.result).toString()) as T;
}

const short = (id: string) => id.split('.')[0] ?? id;
const pct = (x: number) => `${x >= 0 ? '' : '-'}${Math.round(Math.abs(x) * 100)}%`;

const rounds = (await view<Round[]>('get_latest_rounds', { limit: 20 })).filter((r) => r.outcome).sort((a, b) => a.id - b.id);
let notes: { rounds: Record<string, { brain: string; scenario?: string }> } = { rounds: {} };
try {
  notes = JSON.parse(readFileSync(NOTES, 'utf8'));
} catch {
  // No published notes for this contract.
}
const h = headline(
  rounds.map((r) => ({
    buyers: r.buyers.map((b) => ({ id: b.account_id, qty: b.qty, maxPrice: BigInt(b.max_price) })),
    bids: r.sellers.filter((s) => s.revealed).map((s) => ({ id: s.account_id, price: BigInt(s.revealed!.price), capacity: s.revealed!.capacity, commitIndex: s.commit_index })),
    price: r.outcome!.price === null ? null : BigInt(r.outcome!.price),
    demand: r.outcome!.demand,
  })),
);
const multi = rounds.filter((r) => r.fills.length >= 2).length;
const forfeits = rounds.reduce((a, r) => a + r.sellers.filter((s) => !s.revealed).length, 0);
const date = new Date().toISOString().slice(0, 10);
const line =
  `${pct(h.moreUnits).replace(/^(?!-)/, '+')} more compute than a one-winner market, buyers paid ${pct(h.belowMax)} below their max, ` +
  `${multi} of ${rounds.length} rounds shared by 2+ providers (${rounds.length} live testnet rounds on ${CONTRACT}, as of ${date})`;

const rows = rounds
  .map((r) => {
    const n = notes.rounds[String(r.id)];
    const asks = r.sellers.map((s) => `${short(s.account_id)} ${s.revealed ? `${formatUsdc(BigInt(s.revealed.price))}×${s.revealed.capacity}` : 'no reveal'}`).join(', ');
    const fills = r.fills.map((f) => `${short(f.account_id)} ${f.units}`).join(' + ') || '—';
    const price = r.outcome!.price === null ? 'failed' : formatUsdc(BigInt(r.outcome!.price));
    return `| ${r.id} | ${n ? (n.brain.startsWith('nearai:') ? 'AI' : 'scripted') : 'scripted'} | ${n?.scenario ?? 'default'} | ${r.buyers.length} | ${asks} | ${price} | ${r.outcome!.demand} | ${fills} | ${r.price_set_by ? short(r.price_set_by) : '—'} |`;
  })
  .join('\n');

const md = `# Live results on NEAR testnet

Generated by \`npm run live:report\` from \`${CONTRACT}\` on ${date}. Rerun it to refresh; the live page computes the same numbers in the browser.

**Live:** ${line}.

Simulated numbers for comparison: [docs/RESULTS.md](RESULTS.md).

| Round | Agents | Scenario | Buyers | Provider asks (price × capacity) | Price | Units | Sold by | Price named by |
|---|---|---|---|---|---|---|---|---|
${rows}
`;
mkdirSync(resolve('docs'), { recursive: true });
writeFileSync(join(resolve('docs'), 'LIVE.md'), md);

// Refresh the dated live line in the README, between its markers.
const readmePath = resolve('README.md');
const readme = readFileSync(readmePath, 'utf8');
const block = `<!-- live:start -->\n**Live on NEAR testnet:** ${line}. Every round: [docs/LIVE.md](docs/LIVE.md).\n<!-- live:end -->`;
if (/<!-- live:start -->[\s\S]*?<!-- live:end -->/.test(readme)) {
  writeFileSync(readmePath, readme.replace(/<!-- live:start -->[\s\S]*?<!-- live:end -->/, block));
  console.log('README live line updated');
}
console.log(line);
console.log(`Written to ${join(resolve('docs'), 'LIVE.md')}`);
