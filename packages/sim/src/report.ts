import { headline } from '@hivebuy/core';
import { type RoundRecord, runSimulation } from './index.js';

/** The seeds and round count behind every simulated number in the README. */
export const REPORT_SEEDS = [42, 7, 123, 2026] as const;
export const REPORT_ROUNDS_PER_SEED = 50;

const pct = (x: number) => `${Math.round(x * 100)}%`;
const pct1 = (x: number) => `${(x * 100).toFixed(1)}%`;

function summarize(rounds: readonly RoundRecord[]) {
  const h = headline(
    rounds.map((r) => ({ buyers: r.buyers, bids: r.sellers.filter((s) => s.revealed), price: r.result.price, demand: r.result.demand })),
  );
  return {
    ...h,
    rounds: rounds.length,
    cleared: rounds.filter((r) => r.result.status === 'cleared').length,
    multiWinner: rounds.filter((r) => r.result.fills.length >= 2).length,
    forfeits: rounds.reduce((a, r) => a + r.forfeited.length, 0),
  };
}

export interface SimReport {
  /** One line, quoted verbatim in the README (a test checks it). */
  headline: string;
  /** The simulated column of the landing page's "Simulated vs live" table (a test checks it). */
  cells: { rounds: string; more: string; below: string; multi: string; forfeits: string };
  /** Full contents of docs/RESULTS.md. */
  markdown: string;
}

/** Deterministic: same code → same report, byte for byte (no dates), so CI can diff it. */
export function buildReport(): SimReport {
  const perSeed = REPORT_SEEDS.map((seed) => ({ seed, ...summarize(runSimulation({ seed, rounds: REPORT_ROUNDS_PER_SEED }).rounds) }));
  const all = summarize(REPORT_SEEDS.flatMap((seed) => runSimulation({ seed, rounds: REPORT_ROUNDS_PER_SEED }).rounds));
  const line =
    `${pct(all.moreUnits)} more compute bought than a one-winner market, and buyers paid ${pct(all.belowMax)} less than the most they offered ` +
    `(${all.rounds} simulated rounds, seeds ${REPORT_SEEDS.join(', ')})`;
  const rows = [...perSeed, { seed: 'all' as const, ...all }]
    .map(
      (s) =>
        `| ${s.seed} | ${s.rounds} | ${s.cleared} | ${s.multiWinner} | ${s.units} | ${s.oneWinnerUnits} | +${pct1(s.moreUnits)} | ${pct1(s.belowMax)} | ${s.forfeits} |`,
    )
    .join('\n');
  const markdown = `# Simulation results

Generated by \`npm run sim -- --report\`. Do not edit by hand: CI regenerates this file and fails if it differs.

**Headline:** ${line}.

Each seed runs ${REPORT_ROUNDS_PER_SEED} rounds of the scripted market (20 buyer agents, 5 provider agents, no LLM calls) through the same
clearing code as the contract. "One winner" is the rule Hivebuy v1 used: the cheapest single provider that can serve everyone
willing to pay its own ask wins alone.

| Seed | Rounds | Cleared | Rounds with 2+ providers | Units bought | Units with one winner | More compute | Paid below max | Bonds forfeited |
|---|---|---|---|---|---|---|---|---|
${rows}

- **More compute** = units bought ÷ units a one-winner market would have bought − 1.
- **Paid below max** = 1 − (what included buyers paid ÷ what they offered at most), weighted by units.

Live testnet numbers are computed from the contract on the live page, not here.
`;
  const cells = {
    rounds: String(all.cleared),
    more: `+${pct(all.moreUnits)}`,
    below: pct(all.belowMax),
    multi: String(all.multiWinner),
    forfeits: String(all.forfeits),
  };
  return { headline: line, cells, markdown };
}
